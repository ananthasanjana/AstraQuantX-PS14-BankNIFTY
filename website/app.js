  const T0 = M.dte / 365, BAR_YEARS = 5 / 525600, SLIP = M.costs.tick * M.costs.slipTicks;
  const $ = (s, r = document) => r.querySelector(s);
  const $$ = (s, r = document) => [...r.querySelectorAll(s)];

  /* ---------------- formatting ---------------- */
  const inr = (n, sign = false) => {
    if (n == null || isNaN(n)) return "--";
    const s = Math.abs(n).toLocaleString("en-IN", { maximumFractionDigits: 0 });
    return (n < 0 ? "-" : sign && n > 0 ? "+" : "") + "₹" + s;
  };
  const num = (n, d = 2) => (n == null || isNaN(n) ? "--" : Number(n).toLocaleString("en-IN", { minimumFractionDigits: d, maximumFractionDigits: d }));
  const pct = (n, d = 2) => (n == null || isNaN(n) ? "--" : (n > 0 ? "+" : "") + Number(n).toFixed(d) + "%");
  const cls = (n) => (n > 0 ? "pos" : n < 0 ? "neg" : "");
  const pad = (x) => String(x).padStart(2, "0");
  const hhmm = (i) => { const d = new Date(B.t[i] * 1000); return pad(d.getUTCHours()) + ":" + pad(d.getUTCMinutes()); };
  const mins = (i) => { const d = new Date(B.t[i] * 1000); return d.getUTCHours() * 60 + d.getUTCMinutes(); };
  const stamp = (i) => B.day[i].slice(5) + " " + hhmm(i);
  const toHM = (s) => { const [h, m] = s.split(":").map(Number); return h * 60 + m; };
  const ENTRY_START = toHM(M.entryStart), ENTRY_END = toHM(M.entryEnd), SQUARE_OFF = toHM(M.squareOff);
  const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));

  /* ---------------- option pricing + costs (mirror of the Python engine) ---------------- */
  function ncdf(x) {
    const t = 1 / (1 + 0.2316419 * Math.abs(x));
    const d = 0.3989422804 * Math.exp(-x * x / 2);
    const p = d * t * (0.31938153 + t * (-0.356563782 + t * (1.781477937 + t * (-1.821255978 + t * 1.330274429))));
    return x > 0 ? 1 - p : p;
  }
  function bs(S, K, T, kind) {
    T = Math.max(T, 1e-6);
    const sq = M.iv * Math.sqrt(T);
    const d1 = (Math.log(S / K) + (M.rate + 0.5 * M.iv * M.iv) * T) / sq, d2 = d1 - sq;
    return kind === "CE" ? S * ncdf(d1) - K * Math.exp(-M.rate * T) * ncdf(d2)
                         : K * Math.exp(-M.rate * T) * ncdf(-d2) - S * ncdf(-d1);
  }
  function bsDelta(S, K, T, kind) {
    const sq = M.iv * Math.sqrt(T), d1 = (Math.log(S / K) + (M.rate + 0.5 * M.iv * M.iv) * T) / sq;
    return kind === "CE" ? ncdf(d1) : ncdf(d1) - 1;
  }
  const atm = (S) => Math.round(S / M.strikeStep) * M.strikeStep;
  function tradeCosts(buy, sell, qty) {
    const c = M.costs, bv = buy * qty, sv = sell * qty;
    const exch = (bv + sv) * c.exch, sebi = (bv + sv) * c.sebi, brok = 2 * c.brokerage;
    return brok + exch + sebi + sv * c.stt + bv * c.stamp + c.gst * (brok + exch + sebi);
  }
  const riskLots = (buy) => Math.max(1, Math.floor(M.riskPerTrade * M.capital / (M.stop * buy * M.lot)));

